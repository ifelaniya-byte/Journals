FILES = json.loads(base64.b64decode(_ARCHIVE).decode("utf-8"))


def safe_write(root: pathlib.Path, relative: str, content: str, force: bool) -> None:
    destination = root / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() and not force:
        return
    destination.write_text(content, encoding="utf-8")


def build(target: pathlib.Path, force: bool = False) -> None:
    target.mkdir(parents=True, exist_ok=True)
    for relative, content in FILES.items():
        safe_write(target, relative, content, force)
    print(f"OMEGA SELLER STATION CREATED at {target.resolve()} ({len(FILES)} files)")


def self_test() -> int:
    with tempfile.TemporaryDirectory() as directory:
        root = pathlib.Path(directory)
        build(root, force=True)
        result = subprocess.run(
            [sys.executable, "-m", "pytest", "-q"],
            cwd=root, text=True, capture_output=True,
        )
        sys.stdout.write(result.stdout)
        sys.stderr.write(result.stderr)
        print("SELF-TEST:", "PASS" if result.returncode == 0 else "FAIL")
        return result.returncode


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", default=".")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    build(pathlib.Path(args.target).resolve(), force=args.force)
    return 0


